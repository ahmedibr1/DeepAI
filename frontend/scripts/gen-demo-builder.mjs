/* Inlines the built offline DeepDive Builder into a TS module, so the single-file demo can host it
   in a blob: iframe (the portal normally loads /builder.html). Run after `npm run build:offline`. */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../dist-offline/DeepDive_Builder.html");
const target = resolve(here, "../src/demo/builderHtml.ts");

let html = readFileSync(source, "utf8");
html = html.replace("<body>", '<body>\n<script>window.__DD_EMBED__ = true;</script>');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `/* Generated by scripts/gen-demo-builder.mjs — do not edit. */\nexport default ${JSON.stringify(html)};\n`);
console.log(`inlined builder: ${(html.length / 1024).toFixed(0)} KB → src/demo/builderHtml.ts`);
